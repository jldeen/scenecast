//! Compile recorder output into the player configuration.

use serde_json::{Map, Value, json};
use thiserror::Error;

#[derive(Debug, Error)]
pub enum FlowError {
    #[error("recording flow: {0}")]
    Invalid(String),
}

fn array<'a>(value: &'a Value, key: &str) -> Result<&'a [Value], FlowError> {
    match value.get(key) {
        None | Some(Value::Null) => Ok(&[]),
        Some(Value::Array(values)) => Ok(values),
        _ => Err(FlowError::Invalid(format!("{key} must be an array"))),
    }
}

fn object<'a>(value: &'a Value, key: &str) -> Result<Option<&'a Map<String, Value>>, FlowError> {
    match value.get(key) {
        None | Some(Value::Null) => Ok(None),
        Some(Value::Object(values)) => Ok(Some(values)),
        _ => Err(FlowError::Invalid(format!("{key} must be an object"))),
    }
}

fn required<'a>(value: &'a Value, key: &str) -> Result<&'a Value, FlowError> {
    value
        .get(key)
        .ok_or_else(|| FlowError::Invalid(format!("missing {key}")))
}

fn string<'a>(value: &'a Value, key: &str) -> Result<&'a str, FlowError> {
    required(value, key)?
        .as_str()
        .ok_or_else(|| FlowError::Invalid(format!("{key} must be a string")))
}

fn copied(value: &Value, excluded: &[&str]) -> Result<Map<String, Value>, FlowError> {
    let fields = value
        .as_object()
        .ok_or_else(|| FlowError::Invalid("expected an object".into()))?;
    Ok(fields
        .iter()
        .filter(|(key, _)| !excluded.contains(&key.as_str()))
        .map(|(key, value)| (key.clone(), value.clone()))
        .collect())
}

fn push(flow: &mut Value, key: &str, item: Value) {
    flow[key].as_array_mut().expect("flow array").push(item);
}

/// Compile the base flow. JavaScript override and focus modules, if present, run after this step.
pub fn compile_recording(cfg: &Value, rec: &Value, kit_version: &str) -> Result<Value, FlowError> {
    let name = string(cfg, "name")?;
    let apps = array(cfg, "apps")?
        .iter()
        .map(|app| {
            let id = string(app, "id")?;
            let mut out = Map::new();
            out.insert("id".into(), json!(id));
            if let Some(key) = app.get("key") {
                out.insert("key".into(), key.clone());
            }
            out.insert(
                "title".into(),
                json!(
                    app.get("title")
                        .and_then(Value::as_str)
                        .filter(|s| !s.is_empty())
                        .unwrap_or(id)
                ),
            );
            out.insert("layout".into(), json!({}));
            out.insert("on".into(), json!([]));
            Ok(Value::Object(out))
        })
        .collect::<Result<Vec<_>, FlowError>>()?;
    let mut flow = json!({
        "version": 1, "kit": kit_version, "about": "Generated by scenecast from recording.json and flow.overrides.mjs. Edit those, not this file.",
        "name": name, "title": cfg.get("title").and_then(Value::as_str).filter(|s| !s.is_empty()).unwrap_or(name),
        "pace": 5, "apps": apps, "states": {}, "streams": {}, "beats": [],
        "path": rec.get("path").filter(|v| truthy(v)).cloned().unwrap_or_else(|| json!([])),
        "hoverPages": [], "clickPages": [], "drags": [], "variants": [], "lists": [],
        "zoomRefs": [], "notes": array(rec, "notes")?,
    });
    if let Some(states) = object(rec, "states")? {
        for (id, state) in states {
            let mut out = Map::new();
            out.insert("app".into(), required(state, "app")?.clone());
            out.insert("snap".into(), required(state, "snap")?.clone());
            for key in ["title", "focus", "on", "fill", "esc"] {
                if let Some(value) = state.get(key)
                    && truthy(value)
                    && (key != "on" || !array(state, "on")?.is_empty())
                {
                    out.insert(key.into(), value.clone());
                }
            }
            flow["states"][id] = Value::Object(out);
        }
    }
    if let Some(streams) = object(rec, "streams")? {
        for (id, stream) in streams {
            flow["streams"][id] = Value::Object(copied(stream, &["realMs"])?);
        }
    }
    let beats = array(rec, "beats")?;
    if let Some(first) = beats.first() {
        let mut reset = copied(first, &[])?;
        reset.insert("label".into(), json!("0 Reset"));
        push(&mut flow, "beats", Value::Object(reset));
        for (index, beat) in beats.iter().take(9).enumerate() {
            let mut beat = copied(beat, &[])?;
            let label = beat
                .get("label")
                .and_then(Value::as_str)
                .unwrap_or("undefined");
            beat.insert("label".into(), json!(format!("{} {label}", index + 1)));
            push(&mut flow, "beats", Value::Object(beat));
        }
    }
    if beats.len() > 9 {
        push(
            &mut flow,
            "notes",
            json!(format!(
                "{} beats recorded; ⌥1–⌥9 keep the first 9 (pick others in flow.overrides.mjs)",
                beats.len()
            )),
        );
    }
    let sides = rec.get("sides").unwrap_or(&Value::Null);
    for hover in array(sides, "hovers")? {
        if hover.get("frame").is_some_and(|v| !v.is_null() && v != "") {
            push(&mut flow, "hoverPages", hover.clone());
        } else {
            let mut out = Map::new();
            for key in ["page", "app", "base"] {
                if let Some(value) = hover.get(key) {
                    out.insert(key.into(), value.clone());
                }
            }
            push(&mut flow, "hoverPages", Value::Object(out));
        }
    }
    for list in array(sides, "lists")? {
        push(&mut flow, "lists", list.clone());
    }
    for click in array(sides, "clicks")? {
        let mut entry = Map::new();
        for key in ["page", "app", "base", "frame"] {
            if let Some(value) = click.get(key) {
                entry.insert(key.into(), value.clone());
            }
        }
        let mut sticky = Vec::new();
        for result in array(click, "results")? {
            match result.get("restore").and_then(Value::as_str) {
                Some("toggle" | "reopen") if !result.get("portals").is_some_and(truthy) => {
                    sticky.push(required(result, "name")?.clone());
                }
                Some("stuck") => push(
                    &mut flow,
                    "notes",
                    json!(format!(
                        "{}: \"{}\" didn't close the page's way (Escape, again, a control in its place); it's left out unless clickPages restore says how",
                        string(click, "page")?,
                        string(result, "name")?
                    )),
                ),
                _ => {}
            }
        }
        entry.insert("sticky".into(), json!(sticky));
        push(&mut flow, "clickPages", Value::Object(entry));
    }
    for drag in array(sides, "drags")? {
        push(
            &mut flow,
            "drags",
            Value::Object(copied(drag, &["state", "restoredOk"])?),
        );
    }
    compile_groups(&mut flow, array(sides, "groups")?)?;
    for chip in array(sides, "chips")? {
        let app = string(chip, "app")?;
        let rule = Value::Object(copied(chip, &["app", "state"])?);
        let apps = flow["apps"].as_array_mut().expect("apps array");
        if let Some(found) = apps.iter_mut().find(|a| a["id"] == app) {
            let chips = found["layout"]
                .as_object_mut()
                .expect("layout")
                .entry("chips")
                .or_insert_with(|| json!([]));
            chips.as_array_mut().expect("chips").push(rule.clone());
            push(
                &mut flow,
                "variants",
                required(required(&rule, "plus")?, "from")?.clone(),
            );
        }
    }
    compile_zoom(&mut flow, cfg, rec, array(sides, "zoom")?)?;
    for drag in array(rec, "drags")? {
        push(
            &mut flow,
            "notes",
            json!(format!(
                "{}: a drag on {} by {} px; add a drags rule if the pane should resize",
                string(drag, "state")?,
                serde_json::to_string(required(drag, "spec")?).expect("JSON value serializes"),
                required(drag, "dx")?
            )),
        );
    }
    if let Some(engine) = cfg.get("engine")
        && engine.get("modules").is_some()
    {
        flow["modules"] = json!(
            array(engine, "modules")?
                .iter()
                .map(|module| {
                    module
                        .as_str()
                        .map(|module| format!("/demo/{module}"))
                        .ok_or_else(|| FlowError::Invalid("engine module must be a string".into()))
                })
                .collect::<Result<Vec<_>, _>>()?
        );
    }
    Ok(flow)
}

fn truthy(value: &Value) -> bool {
    match value {
        Value::Null => false,
        Value::Bool(v) => *v,
        Value::Number(v) => v.as_f64().is_some_and(|n| n != 0.0),
        Value::String(v) => !v.is_empty(),
        Value::Array(_) | Value::Object(_) => true,
    }
}

fn compile_groups(flow: &mut Value, groups: &[Value]) -> Result<(), FlowError> {
    let mut app_ids = Vec::new();
    for group in groups {
        let app = string(group, "app")?;
        if !app_ids.contains(&app) {
            app_ids.push(app);
        }
    }
    let mut output = Vec::new();
    for app in app_ids {
        let recs: Vec<_> = groups.iter().filter(|g| g["app"] == app).collect();
        let mut opened = Vec::new();
        for rec in &recs {
            for group in array(rec, "groups")? {
                if group.get("opened").is_some_and(truthy) {
                    opened.push((*rec, group));
                } else {
                    push(
                        flow,
                        "notes",
                        json!(format!(
                            "{}: the step group \"{}\" didn't open",
                            string(rec, "state")?,
                            string(group, "label")?
                        )),
                    );
                }
            }
        }
        let Some((template_rec, template)) = opened
            .iter()
            .find(|(_, group)| group["kind"] == "list")
            .or_else(|| opened.first())
            .copied()
        else {
            continue;
        };
        let grid = opened
            .iter()
            .find(|(_, group)| group["kind"] == "grid")
            .map(|(_, group)| *group);
        let mut open = Vec::new();
        for rec in &recs {
            let opened = required(rec, "open")?.clone();
            push(flow, "variants", opened.clone());
            open.push(json!({"open": opened, "closed": required(rec, "closed")?}));
        }
        let streams: Vec<_> = flow["streams"]
            .as_object()
            .expect("streams")
            .iter()
            .filter_map(|(name, stream)| {
                let target = stream.get("to")?.as_str()?;
                (flow["states"][target]["app"] == app).then(|| name.clone())
            })
            .collect();
        let mut result = Map::new();
        result.insert("app".into(), json!(app));
        for key in ["button", "label", "chevron"] {
            if let Some(value) = recs[0].get(key) {
                result.insert(key.into(), value.clone());
            }
        }
        result.insert(
            "template".into(),
            json!({
                "closed": required(template_rec, "closed")?,
                "open": required(template_rec, "open")?,
                "label": required(template, "label")?,
            }),
        );
        result.insert("open".into(), json!(open));
        result.insert("streams".into(), json!(streams));
        if let Some(grid) = grid {
            result.insert("grid".into(), json!({"closed": required(grid, "closedOnly")?, "open": required(grid, "openOnly")?}));
        }
        output.push(Value::Object(result));
    }
    if !groups.is_empty() {
        flow["groups"] = json!(output);
    }
    Ok(())
}

fn compile_zoom(
    flow: &mut Value,
    cfg: &Value,
    rec: &Value,
    zooms: &[Value],
) -> Result<(), FlowError> {
    // The bands are placed from the window the zoom levels were captured in (bw, or a level's width times its zoom),
    // then the recording's window, and only then demo.json's viewport (as flow.mjs).
    let positive = |v: Option<&Value>| v.and_then(Value::as_f64).filter(|v| *v > 0.0);
    let cfg_base = positive(rec.pointer("/viewport/width"))
        .or_else(|| positive(cfg.pointer("/viewport/width")))
        .unwrap_or(1920.0);
    let apps = flow["apps"]
        .as_array()
        .expect("apps")
        .iter()
        .map(|app| string(app, "id").map(str::to_owned))
        .collect::<Result<Vec<_>, _>>()?;
    for (index, app) in apps.iter().enumerate() {
        let zs: Vec<_> = zooms.iter().filter(|z| z["app"] == *app).collect();
        let mut levels = Vec::new();
        for zoom in &zs {
            let level = required(zoom, "z")?
                .as_f64()
                .ok_or_else(|| FlowError::Invalid("zoom level must be numeric".into()))?;
            if level < 100.0 {
                push(flow, "zoomRefs", (*zoom).clone());
            }
            if level > 100.0 && !levels.contains(&level) {
                levels.push(level);
            }
        }
        levels.sort_by(f64::total_cmp);
        if levels.is_empty() {
            continue;
        }
        let base = zs
            .iter()
            .filter(|z| z["z"].as_f64().is_some_and(|l| l > 100.0))
            .find_map(|z| {
                positive(z.get("bw")).or_else(|| {
                    positive(z.get("vw"))
                        .map(|vw| (vw * z["z"].as_f64().unwrap_or(100.0) / 100.0).round())
                })
            })
            .unwrap_or(cfg_base);
        let mut prev = base;
        let mut bands = Vec::new();
        for level in levels {
            let width = (base * 100.0 / level).round();
            // A level whose markup was the same as the one below (not captured) moves the band's start down to it.
            let from = zs
                .iter()
                .filter(|z| z["z"].as_f64() == Some(level))
                .filter_map(|z| positive(z.get("pw")))
                .fold(prev, f64::min);
            let mut variants = Map::new();
            for zoom in zs.iter().filter(|z| z["z"].as_f64() == Some(level)) {
                variants.insert(
                    string(zoom, "state")?.to_owned(),
                    required(zoom, "snap")?.clone(),
                );
                push(flow, "variants", required(zoom, "snap")?.clone());
                push(flow, "zoomRefs", (*zoom).clone());
            }
            bands
                .push(json!({"below": ((from + width) / 2.0).round() as i64, "variant": variants}));
            prev = width;
        }
        flow["apps"][index]["layout"]["responsive"] =
            json!([{"part":{"sel":"body","css":"<body[\\s>]","up":0},"bands":bands}]);
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn compiles_recorded_interactions_groups_chips_and_zoom() {
        let cfg = json!({
            "name": "fixture",
            "viewport": {"width": 1600},
            "apps": [{"id": "chat", "key": "C"}]
        });
        let rec = json!({
            "states": {
                "start": {"app":"chat","snap":"start","sig":"ignored","on":[{"click":{"sel":"button"},"to":"answer"}]},
                "answer": {"app":"chat","snap":"answer"}
            },
            "streams": {"s1":{"to":"answer","frames":[0,1],"realMs":123}},
            "beats": [{"label":"start","active":"chat","states":{"chat":"start"}}],
            "sides": {
                "hovers": [{"page":"start","app":"chat","base":"start","extra":"ignored"}],
                "clicks": [{"page":"start","app":"chat","base":"start","results":[
                    {"name":"panel","restore":"toggle"},
                    {"name":"menu","restore":"escape"},
                    {"name":"stuck","restore":"stuck"}
                ]}],
                "drags": [{"app":"chat","state":"start","restoredOk":true,"dx":5}],
                "groups": [{"app":"chat","state":"answer","closed":"answer","open":"group-open","button":"button",
                    "groups":[{"kind":"list","label":"Steps","opened":true}]}],
                "chips": [{"app":"chat","state":"start","plus":{"from":"chip-source","marker":"more"}}],
                "zoom": [
                    {"app":"chat","state":"start","snap":"small","z":67},
                    {"app":"chat","state":"start","snap":"large","z":150}
                ]
            }
        });
        let flow = compile_recording(&cfg, &rec, "0.2.0").unwrap();
        assert_eq!(flow["states"]["start"]["on"][0]["to"], "answer");
        assert!(flow["states"]["start"].get("sig").is_none());
        assert!(flow["streams"]["s1"].get("realMs").is_none());
        assert_eq!(flow["beats"][0]["label"], "0 Reset");
        assert_eq!(flow["beats"][1]["label"], "1 start");
        assert_eq!(
            flow["hoverPages"][0],
            json!({"page":"start","app":"chat","base":"start"})
        );
        assert_eq!(flow["clickPages"][0]["sticky"], json!(["panel"]));
        assert!(flow["notes"][0].as_str().unwrap().contains("stuck"));
        assert!(flow["drags"][0].get("state").is_none());
        assert_eq!(flow["groups"][0]["streams"], json!(["s1"]));
        assert_eq!(
            flow["variants"],
            json!(["group-open", "chip-source", "large"])
        );
        assert_eq!(
            flow["apps"][0]["layout"]["responsive"][0]["bands"][0]["below"],
            1334
        );
        assert_eq!(flow["zoomRefs"].as_array().unwrap().len(), 2);
    }

    #[test]
    fn zoom_bands_come_from_the_recorded_window_not_demo_json() {
        let cfg = json!({"name": "fx", "viewport": {"width": 1920}, "apps": [{"id": "chat"}]});
        let rec = json!({
            "viewport": {"width": 1374, "height": 733, "dpr": 2.2},
            "states": {"start": {"app":"chat","snap":"start"}},
            "sides": {"zoom": [
                {"app":"chat","state":"start","snap":"v150-start","z":150,"vw":916,"bw":1374,"pw":1099},
                {"app":"chat","state":"start","snap":"v200-start","z":200,"vw":687,"pw":916}
            ]}
        });
        let flow = compile_recording(&cfg, &rec, "0.2.0").unwrap();
        let bands = &flow["apps"][0]["layout"]["responsive"][0]["bands"];
        // 110% and 125% looked as 100%: the 150% band starts halfway from 125% (1099), below the 1374 window.
        assert_eq!(bands[0]["below"], 1008);
        assert_eq!(bands[1]["below"], 802);
        // An older recording: no bw or pw, the base from a level's width times its zoom.
        let old = json!({"states": rec["states"], "sides": {"zoom": [{"app":"chat","state":"start","snap":"v110-start","z":110,"vw":1249}]}});
        let flow = compile_recording(&cfg, &old, "0.2.0").unwrap();
        assert_eq!(
            flow["apps"][0]["layout"]["responsive"][0]["bands"][0]["below"],
            1312
        );
    }

    #[test]
    fn rejects_malformed_recording_sections() {
        let cfg = json!({"name":"fixture","apps":[{"id":"chat"}]});
        assert!(compile_recording(&cfg, &json!({"states":[]}), "0.2.0").is_err());
        assert!(
            compile_recording(&cfg, &json!({"states":{"start":{"app":"chat"}}}), "0.2.0").is_err()
        );
    }
}
