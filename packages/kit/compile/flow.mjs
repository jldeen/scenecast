// Writes flow.json from the recording (recording.json, the recorder's output) and the demo's hand edits
// (flow.overrides.mjs). Edit those two, never flow.json itself.
//   node compile/flow.mjs --demo <dir> [--from-raw]
// --from-raw first copies the recorder's raw recording (raw/recording.json) into the demo folder, without its log
// and page URLs. The flow format is in docs/flow-format.md.
import { statSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { loadDemo, KIT_VERSION, FLOW_VERSION } from '../lib/demo.mjs';
import { applyFixesToFlow, readFixes } from '../../fixer/patches.mjs';
import { mergeFocus } from '../../player/app/focus-order.js';
import { plainLabels } from '../lib/beats.mjs';
import { writeRecordingNotes } from '../lib/notes.mjs';
import { readEditorOverrides, applyEditorOverrides, readFocusJson } from '../lib/overrides.mjs';
import { compileEdits } from '../lib/edits.mjs';
import { flowPacks } from '../../apps/build.mjs';

export async function compileFlow(demo, { fromRaw = false } = {}) {
  // A demo without a recording (a flow written by hand) is its own flow.json.
  if (!fromRaw && !existsSync(join(demo.dir, 'recording.json')) && !existsSync(join(demo.raw, 'recording.json')) && existsSync(demo.flowPath)) {
    const flow = JSON.parse(readFileSync(demo.flowPath, 'utf8'));
    flowPacks(flow, demo.cfg);
    return { flow, problems: validate(flow), handWritten: true };
  }
  const recFile = join(demo.dir, 'recording.json');
  const rawFile = join(demo.raw, 'recording.json');
  // A newer take (Record again) replaces the demo's copy; hand edits live in flow.overrides.mjs, not in it.
  const newerTake = existsSync(rawFile) && existsSync(recFile) && statSync(rawFile).mtimeMs > statSync(recFile).mtimeMs;
  if (fromRaw || newerTake || !existsSync(recFile)) {
    const raw = rawFile;
    if (!existsSync(raw)) throw new Error(`no recording: ${raw} (record the demo first: scenecast record start)`);
    const r = JSON.parse(readFileSync(raw, 'utf8'));
    delete r.log;
    for (const a of r.apps || []) delete a.url;
    writeFileSync(recFile, JSON.stringify(r, null, 1) + '\n');
  }
  const rec = JSON.parse(readFileSync(recFile, 'utf8'));
  const cfg = demo.cfg;
  const flow = {
    version: FLOW_VERSION,
    kit: KIT_VERSION,
    about: 'Generated by scenecast from recording.json and flow.overrides.mjs. Edit those, not this file.',
    name: cfg.name,
    title: cfg.title || cfg.name,
    // Seconds per streamed answer at pace 5 = the recorded speed (each stream capped at record.streamMaxMs).
    pace: 5,
    apps: cfg.apps.map(a => ({ id: a.id, key: a.key, title: a.title || a.id, layout: {}, on: [] })),
    states: {},
    streams: {},
    beats: [],
    path: rec.path || [],
    hoverPages: [],
    clickPages: [],
    drags: [],
    variants: [],
    lists: [],
    zoomRefs: [],
    notes: [...(rec.notes || [])],
  };
  for (const [id, s] of Object.entries(rec.states || {})) {
    const st = { app: s.app, snap: s.snap };
    if (s.title) st.title = s.title;
    if (s.focus) st.focus = s.focus;
    if (s.on && s.on.length) st.on = s.on;
    if (s.fill) st.fill = s.fill;
    if (s.esc) st.esc = s.esc;
    flow.states[id] = st;
  }
  for (const [name, s] of Object.entries(rec.streams || {})) {
    const { realMs, ...rest } = s;
    flow.streams[name] = rest;
  }
  // Beats: ⌥0 resets to the start, ⌥1 … ⌥9 jump to the start, each app switch and each streamed answer, in order.
  const beats = rec.beats || [];
  if (beats.length) flow.beats = [{ ...beats[0], label: '0 Reset' }, ...beats.slice(0, 9).map((b, i) => ({ ...b, label: `${i + 1} ${b.label}` }))];
  if (beats.length > 9) flow.notes.push(`${beats.length} beats recorded; ⌥1–⌥9 keep the first 9 (pick others in flow.overrides.mjs)`);
  const sides = rec.sides || {};
  for (const h of sides.hovers || []) flow.hoverPages.push(h.frame ? h : { page: h.page, app: h.app, base: h.base });
  for (const l of sides.lists || []) flow.lists.push(l);
  // Clicks: panes and sections that open or close in place (the control again, or a control in its place, undoes
  // them) stay as she left them when the page changes (sticky), until ⌥0 or a beat jump. Menus and popups don't.
  for (const c of sides.clicks || []) {
    const ok = c.results.filter(r => r.restore && r.restore !== 'stuck');
    flow.clickPages.push({ page: c.page, app: c.app, base: c.base, frame: c.frame, sticky: ok.filter(r => /^(toggle|reopen)$/.test(r.restore) && !r.portals).map(r => r.name) });
    for (const r of c.results.filter(r => r.restore === 'stuck')) flow.notes.push(`${c.page}: "${r.name}" didn't close the page's way (Escape, again, a control in its place); it's left out unless clickPages restore says how`);
  }
  for (const d of sides.drags || []) { const { state, restoredOk, ...rule } = d; flow.drags.push(rule); }
  // Step groups: one entry per app, from every screen they were opened on. The first list group's screen is the
  // closed/open template; a grid group (list kept in the page) gives the classes its region swaps.
  const groupApps = [...new Set((sides.groups || []).map(g => g.app))];
  if (groupApps.length) flow.groups = groupApps.map(app => {
    const recs = sides.groups.filter(g => g.app === app);
    const ok = recs.flatMap(r => r.groups.filter(g => g.opened).map(g => ({ r, g })));
    const t = ok.find(x => x.g.kind === 'list') || ok[0];
    const grid = ok.find(x => x.g.kind === 'grid');
    for (const r of recs) for (const g of r.groups.filter(g => !g.opened)) flow.notes.push(`${r.state}: the step group "${g.label}" didn't open`);
    if (!t) return null;
    for (const r of recs) flow.variants.push(r.open);
    return { app, button: recs[0].button, label: recs[0].label, chevron: recs[0].chevron,
      template: { closed: t.r.closed, open: t.r.open, label: t.g.label },
      open: recs.map(r => ({ open: r.open, closed: r.closed })),
      streams: Object.keys(flow.streams).filter(n => (flow.states[flow.streams[n].to] || {}).app === app),
      grid: grid ? { closed: grid.g.closedOnly, open: grid.g.openOnly } : undefined };
  }).filter(Boolean);
  // "+N" chips: a layout rule on the app; its chip comes from the narrowed capture.
  for (const ch of sides.chips || []) {
    const { app, state, ...rule } = ch;
    const a = flow.apps.find(x => x.id === app); if (!a) continue;
    (a.layout.chips = a.layout.chips || []).push(rule);
    flow.variants.push(rule.plus.from);
  }
  // Zoom: above 100% the page is swapped for its capture at the nearest zoom (whole body, per state); below 100%
  // the captures are references for the zoom check only.
  // The bands are placed from the window the zoom levels were captured in (bw, or a level's width × its zoom), not
  // demo.json's viewport: a real Chrome window at 1374 px got bands for 1920 and the replica swapped to its 110%
  // layout at full size.
  const cfgBase = (rec.viewport && rec.viewport.width) || (cfg.viewport && cfg.viewport.width) || 1920;
  for (const app of flow.apps) {
    const zs = (sides.zoom || []).filter(z => z.app === app.id);
    for (const z of zs.filter(z => z.z < 100)) flow.zoomRefs.push(z);
    const up = zs.filter(z => z.z > 100);
    if (!up.length) continue;
    const b0 = up.find(z => z.bw > 0 || z.vw > 0);
    const base = b0 ? (b0.bw > 0 ? b0.bw : Math.round(b0.vw * b0.z / 100)) : cfgBase;
    const levels = [...new Set(up.map(z => z.z))].sort((a, b) => a - b);
    let prevW = base;
    const bands = [];
    for (const lv of levels) {
      const at = up.filter(z => z.z === lv);
      const w = Math.round(base * 100 / lv);
      // A level whose markup was the same as the one below (not captured) moves the band's start down to it.
      const pws = at.map(z => z.pw).filter(v => v > 0);
      const from = pws.length ? Math.min(prevW, ...pws) : prevW;
      bands.push({ below: Math.round((from + w) / 2), variant: Object.fromEntries(at.map(z => [z.state, z.snap])) });
      prevW = w;
      for (const z of at) { flow.variants.push(z.snap); flow.zoomRefs.push(z); }
    }
    app.layout.responsive = [{ part: { sel: 'body', css: '<body[\\s>]', up: 0 }, bands }];
  }
  for (const d of rec.drags || []) flow.notes.push(`${d.state}: a drag on ${JSON.stringify(d.spec)} by ${d.dx} px; add a drags rule if the pane should resize`);
  // The demo's own engine modules (demo.json engine.modules), loaded by the shell.
  if (cfg.engine && cfg.engine.modules) flow.modules = cfg.engine.modules.map(m => '/demo/' + m);
  return finishFlow(demo, flow, rec);
}

export async function finishFlow(demo, flow, rec) {
  const cfg = demo.cfg;
  // The fidelity loop's fixes for this demo (flow.fixes.json, written by scenecast fidelity), before the hand edits.
  applyFixesToFlow(flow, readFixes(demo.dir));
  // Beat labels in plain words ("3 Copilot: Library"), before the hand edits so those can rename them.
  plainLabels(flow);
  // Hand edits last.
  const over = join(demo.dir, 'flow.overrides.mjs');
  if (existsSync(over)) {
    const mod = await import(pathToFileURL(over).href + '?t=' + Date.now());
    const out = await mod.default(flow, { recording: rec, demo: cfg });
    if (out) Object.assign(flow, out);
  }
  // App packs (packages/apps): the named layout and drag rules the demo references ({ use: name }), the rules every
  // demo of an app gets, step-group selectors, menu items that load late and menu CSS. After the hand edits (they can
  // replace flow.apps), and the demo's own entries always win.
  flowPacks(flow, cfg);
  // The editor's changes (flow.editor.json: wording and date edits, beat starts), after the hand edits, so what was
  // set in the replica wins.
  applyEditorOverrides(flow, readEditorOverrides(demo.dir));
  // Focus points (⌥F, engine/app/focus.js): the demo's focus.mjs, whose default export is the points (or a function
  // of the flow that returns them) and whose `options` export can set { zoom, pen, color }, and focus.json (written
  // by scenecast script and the editor's dots), merged in beat order. The kit's focus module loads when there are any.
  const fp = join(demo.dir, 'focus.mjs');
  let hand = [];
  if (existsSync(fp)) {
    const m = await import(pathToFileURL(fp).href + '?t=' + Date.now());
    hand = (typeof m.default === 'function' ? await m.default(flow) : m.default) || [];
    if (m.options) flow.focusOptions = m.options;
  }
  // Points from an earlier script (focus.json) can name beats or screens a new take doesn't have: they're left out until
  // Script makes new ones, instead of stopping the build (Nov 20: Record for me again, then Build, failed on one).
  const nBeats = (flow.beats || []).length, S = flow.states || {};
  const fits = p => (!Number.isInteger(p.beat) || p.beat < nBeats) && (p.states || []).every(id => S[id]) && (!p.via || [...(p.via.from || []), p.via.to].every(id => S[id]));
  const all = readFocusJson(demo.dir).points, generated = all.filter(fits);
  if (generated.length < all.length) (flow.notes = flow.notes || []).push(`${all.length - generated.length} focus point(s) from an earlier script left out (${all.filter(p => !fits(p)).map(p => p.id).join(', ')}): this recording has no such beat or screen; Script makes new ones`);
  if (existsSync(fp) || generated.length) flow.focus = mergeFocus(generated, hand, flow);
  // A wording or date change (flow.edits: the editor's, scenecast text) changes the words a focus point looks for
  // too: a point made from the script still finds its sentence after "Friday" becomes "Monday".
  if ((flow.focus || []).length && (flow.edits || []).length) flow.focus = focusAfterEdits(flow.focus, flow.edits, flow.states || {});
  if ((flow.focus || []).length) flow.modules = ['/app/focus-module.js', ...(flow.modules || [])];
  const problems = validate(flow);
  writeFileSync(demo.flowPath, JSON.stringify(flow, null, 1) + '\n');
  return { flow, problems };
}

export function focusAfterEdits(points, edits, states) {
  const compiled = compileEdits(edits);
  return points.map(p => {
    const snaps = (p.states || []).map(id => states[id] && states[id].snap).filter(Boolean);
    const apply = t => { for (const e of compiled) { if (e.in && !snaps.some(id => e.in.includes(id))) continue; t = t.replace(e.re, e.to); } return t; };
    const out = { ...p };
    if (typeof p.find === 'string') out.find = apply(p.find);
    if (Array.isArray(p.union)) out.union = p.union.map(u => typeof u === 'string' ? apply(u) : u && typeof u.text === 'string' ? { ...u, text: apply(u.text) } : u);
    return out;
  });
}

// Every state, stream and beat a flow names has to exist.
export function validate(flow) {
  const out = [];
  const S = flow.states || {};
  const apps = new Set((flow.apps || []).map(a => a.id));
  const has = (id, where) => { if (id && !S[id]) out.push(`${where}: no state ${id}`); };
  for (const [id, s] of Object.entries(S)) {
    if (!apps.has(s.app)) out.push(`${id}: no app ${s.app}`);
    if (!s.snap) out.push(`${id}: no snap`);
    has(s.esc, `${id}.esc`);
    for (const t of s.on || []) {
      if (t.stream && !(flow.streams || {})[t.stream]) out.push(`${id}: no stream ${t.stream}`);
      has(t.to, id); has(t.empty, id); has(t.on, id); has(t.off, id);
      for (const v of Object.values(t.query || {})) has(v, id);
    }
    for (const f of s.fill || []) if (f.value === undefined) out.push(`${id}: a fill with no value`);
  }
  for (const a of flow.apps || []) for (const t of a.on || []) { has(t.to, a.id); for (const w of t.when || []) has(w, a.id + '.when'); }
  for (const g of [].concat(flow.groups || [])) { if (!apps.has(g.app)) out.push(`groups: no app ${g.app}`); if (!g.template || !g.template.closed || !g.template.open || !g.template.label) out.push(`groups (${g.app}): no template { closed, open, label }`); for (const s of g.streams || []) if (!(flow.streams || {})[s]) out.push(`groups (${g.app}): no stream ${s}`); }
  for (const [n, s] of Object.entries(flow.streams || {})) has(s.to, 'stream ' + n);
  (flow.beats || []).forEach((b, i) => { if (!apps.has(b.active)) out.push(`beat ${i}: no app ${b.active}`); for (const [a, st] of Object.entries(b.states || {})) { if (!apps.has(a)) out.push(`beat ${i}: no app ${a}`); has(st, `beat ${i}`); } });
  if (!(flow.beats || []).length) out.push('no beats: the replica needs beats[0] (where ⌥0 resets to)');
  const fids = new Set();
  for (const p of flow.focus || []) {
    const w = `focus ${p.id || '(no id)'}`;
    if (!p.id || fids.has(p.id)) out.push(`${w}: needs an id of its own`); fids.add(p.id);
    if (!apps.has(p.app)) out.push(`${w}: no app ${p.app}`);
    if (!(p.states || []).length) out.push(`${w}: no states`); for (const st of p.states || []) has(st, w);
    if (!p.find && !(p.union || []).length) out.push(`${w}: needs find (text) or union (texts or { sel } / { text, up })`);
    if (p.via) { if (!(p.via.from || []).length) out.push(`${w}: via needs from: [states]`); for (const st of p.via.from || []) has(st, `${w}.via`); has(p.via.to, `${w}.via`); }
    if (!Number.isInteger(p.beat) || p.beat < 0 || p.beat > 9) out.push(`${w}: beat must be 0–9 (the ⌥ key that lands just before it)`);
  }
  for (const st of flow.apps || []) if (flow.beats && flow.beats[0] && !flow.beats[0].states[st.id]) out.push(`beat 0: no state for ${st.id}`);
  const keys = (flow.apps || []).map(a => a.key).filter(Boolean).map(k => k.toUpperCase());
  if (new Set(keys).size !== keys.length) out.push('two apps share a key');
  for (const k of keys) if (!/^[A-Z]$/.test(k) || 'FGPN'.includes(k)) out.push(`app key ${k} must be one letter A-Z, not F, G, N or P (presenter keys)`);
  return out;
}

if (process.argv[1] && process.argv[1].endsWith('flow.mjs')) {
  const args = process.argv.slice(2);
  const demo = loadDemo(args);
  const { flow, problems } = args.includes('--compiled-flow')
    ? await finishFlow(demo, JSON.parse(readFileSync(process.env.SCENECAST_FLOW_BASE, 'utf8')), JSON.parse(readFileSync(join(demo.dir, 'recording.json'), 'utf8')))
    : await compileFlow(demo, { fromRaw: args.includes('--from-raw') });
  console.log(`flow.json: ${Object.keys(flow.states).length} states, ${Object.keys(flow.streams).length} streams, ${flow.beats.length} beats, ${flow.path.length} steps`);
  for (const n of flow.notes) console.log('note: ' + n);
  for (const p of problems) console.log('PROBLEM: ' + p);
  if (!problems.length && writeRecordingNotes(demo, flow)) console.log('presenter guide: each beat\'s steps from the recording (no script yet)');
  process.exit(problems.length ? 1 : 0);
}
